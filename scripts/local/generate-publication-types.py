#!/usr/bin/env python3
"""Generate bounded frontend types from the implemented OpenAPI (PyYAML)."""

import argparse
import hashlib
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "services/assessment-service/contracts/publications.openapi.yaml"
TARGET = ROOT / "frontend/features/assessments/api/publication-contract.generated.ts"
NAMES = (
    "Configuration",
    "OwnerView",
    "StudentView",
    "Update",
    "Open",
    "Schedule",
    "ClosedPublication",
    "TeacherCommand",
    "TeacherResults",
    "TeacherResultRow",
    "Result",
    "ClosureView",
    "ClosureCompletion",
    "NotificationPage",
    "Notification",
)


def object_field(name, required, schema):
    optional = "" if name in required else "?"
    prefix = f"  readonly {name}{optional}:"
    value = typescript(schema)
    if len(prefix) + len(value) + 2 <= 80:
        return f"{prefix} {value};"
    if " | " not in value:
        return f"{prefix}\n    {value};"
    if len(value) + 5 <= 80:
        return f"{prefix}\n    {value};"
    return prefix + "\n    | " + "\n    | ".join(value.split(" | ")) + ";"


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for union in ("oneOf", "anyOf"):
        if union in schema:
            return " | ".join(typescript(item) for item in schema[union])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(typescript({"type": item}) for item in kind)
    if kind == "object":
        required = schema.get("required", [])
        fields = [
            object_field(name, required, value)
            for name, value in schema["properties"].items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    if kind == "array":
        return f"ReadonlyArray<{typescript(schema['items'])}>"
    if kind not in ("string", "integer", "number", "boolean", "null"):
        raise ValueError(f"Unsupported schema: {schema}")
    return "number" if kind == "integer" else kind


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = SOURCE.read_bytes()
    schemas = yaml.safe_load(content)["components"]["schemas"]
    # Formatting is intentionally Prettier-compatible for generated union aliases.
    output = ("// Generated by scripts/local/generate-publication-types.py; do not edit.\n"
              "// Source: services/assessment-service/contracts/publications.openapi.yaml\n"
              f"// SHA-256: {hashlib.sha256(content).hexdigest()}\n\n")
    output += "\n\n".join(f"export type {name} = {typescript(schemas[name])};" for name in NAMES) + "\n"
    if args.check:
        if TARGET.read_text() != output:
            raise SystemExit("Publication types are stale; run the generator.")
        print("PASS Publication types match implemented OpenAPI")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(output)


if __name__ == "__main__":
    main()
