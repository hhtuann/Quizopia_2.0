#!/usr/bin/env python3
"""Derive Task2 client types from implemented service OpenAPI; no Task3 UI."""
import argparse
import hashlib
from pathlib import Path
import runpy
import shutil
import subprocess
import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "services/assessment-service/contracts/teacher-assessments.openapi.yaml"
TARGET = ROOT / "frontend/features/teacher-results/api/teacher-assessment-contract.generated.ts"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    typescript = runpy.run_path(str(Path(__file__).with_name("generate-publication-types.py")))["typescript"]
    content = SOURCE.read_bytes()
    schemas = yaml.safe_load(content)["components"]["schemas"]
    output = ("// Generated by scripts/local/generate-teacher-assessment-types.py; do not edit.\n"
              "// Source: services/assessment-service/contracts/teacher-assessments.openapi.yaml\n"
              f"// SHA-256: {hashlib.sha256(content).hexdigest()}\n\n"
              'import type { Result, QuestionReview } from "../../attempts/api/attempt-contract.generated";\n\n')
    output += "\n\n".join(f"export type {name} = {typescript(schema)};" for name, schema in schemas.items()) + "\n"
    pnpm = shutil.which("pnpm") or shutil.which("pnpm.cmd")
    if not pnpm:
        raise SystemExit("pnpm is required to format derived contracts")
    output = subprocess.run([pnpm, "exec", "prettier", "--stdin-filepath", str(TARGET)],
                            input=output, text=True, encoding="utf-8", capture_output=True,
                            check=True, cwd=ROOT / "frontend").stdout
    if args.check:
        if TARGET.read_text(encoding="utf-8") != output:
            raise SystemExit("Teacher assessment types are stale; run generator.")
        print("PASS Teacher assessment client types match implemented OpenAPI")
    else:
        TARGET.write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
