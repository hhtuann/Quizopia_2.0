#!/usr/bin/env python3
"""Derive safe Classroom directory types from canonical OpenAPI (PyYAML)."""

import argparse
import hashlib
import runpy
from pathlib import Path

import yaml
typescript = runpy.run_path(str(Path(__file__).with_name("generate-publication-types.py")))["typescript"]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    source = root / "services/classroom-service/contracts/classroom-directory.openapi.yaml"
    target = root / "frontend/features/classrooms/api/classroom-contract.generated.ts"
    content = source.read_bytes()
    schemas = yaml.safe_load(content)["components"]["schemas"]
    output = ("// Generated by scripts/local/generate-classroom-types.py; do not edit.\n"
              "// Source: services/classroom-service/contracts/classroom-directory.openapi.yaml\n"
              f"// SHA-256: {hashlib.sha256(content).hexdigest()}\n\n")
    output += "\n\n".join(f"export type {name} = {typescript(schemas[name])};"
                          for name in ("ClassroomSummary", "ClassroomPage")) + "\n"
    if args.check:
        if target.read_text() != output:
            raise SystemExit("Classroom types are stale; run the generator.")
        print("PASS Classroom types match canonical OpenAPI")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
